# values containing person names, matched by pattern to keep the names out of this file;
# the named group becomes the remaining dimensions
PATTERN_MAPPING = [
  [/\A(?<dimensions>.+: Transkript\s+.+: Interview, Redaktion), insgesamt 141 Minuten\z/,
   { 'duration' => 'insgesamt 141 Minuten' }]
].freeze

def mapping_for(original)
  return MAPPING[original] if MAPPING.key?(original)

  PATTERN_MAPPING.each do |pattern, row|
    match = pattern.match(original)
    return row.merge('dimensions' => match[:dimensions]) if match
  end
  nil
end

def conn
  ActiveRecord::Base.connection
end

def q(value)
  conn.quote(value)
end

def normalize(string)
  string.to_s.gsub("\n", '⏎').gsub("\t", ' ').strip
end

def owner_condition(md)
  md['media_entry_id'] ? "media_entry_id = #{q(md['media_entry_id'])}" : "collection_id = #{q(md['collection_id'])}"
end

def stats
  @stats ||= Hash.new(0)
end

def report(title)
  puts "\n== #{title}"
  ([SOURCE, DURATION] + TEXT_TARGETS.values + KEYWORD_TARGETS.values).uniq.each do |id|
    next unless MetaKey.exists?(id)

    puts format('%-45s meta_data: %5d  keywords: %4d', id,
                MetaDatum.where(meta_key_id: id).count, Keyword.where(meta_key_id: id).count)
  end
end

def find_meta_datum(meta_key_id, md)
  conn.select_one("SELECT id, string FROM meta_data WHERE meta_key_id = #{q(meta_key_id)} AND #{owner_condition(md)}")
end

def create_meta_datum(meta_key_id, type, md, string = nil)
  conn.select_value(<<~SQL)
    INSERT INTO meta_data (meta_key_id, type, media_entry_id, collection_id, created_by_id, string)
    VALUES (#{q(meta_key_id)}, #{q(type)}, #{q(md['media_entry_id'])}, #{q(md['collection_id'])},
            #{q(md['created_by_id'])}, #{q(string)})
    RETURNING id
  SQL
end

def add_text(meta_key_id, md, value)
  existing = find_meta_datum(meta_key_id, md)
  if existing.nil?
    create_meta_datum(meta_key_id, 'MetaDatum::Text', md, value)
    stats["#{meta_key_id} created"] += 1
  elsif existing['string'].to_s.include?(value)
    stats["#{meta_key_id} already contained"] += 1
  else
    conn.execute("UPDATE meta_data SET string = #{q("#{existing['string']}; #{value}")} WHERE id = #{q(existing['id'])}")
    stats["#{meta_key_id} appended"] += 1
  end
end

def keyword_id(meta_key_id, term, creator_id)
  @keyword_ids ||= {}
  @keyword_ids[[meta_key_id, term]] ||=
    conn.select_value("SELECT id FROM keywords WHERE meta_key_id = #{q(meta_key_id)} AND term = #{q(term)}") ||
    begin
      stats["#{meta_key_id} keywords created"] += 1
      conn.select_value(<<~SQL)
        INSERT INTO keywords (meta_key_id, term, creator_id)
        VALUES (#{q(meta_key_id)}, #{q(term)}, #{q(creator_id)}) RETURNING id
      SQL
    end
end

def add_keyword(meta_key_id, md, term)
  kw_id = keyword_id(meta_key_id, term, md['created_by_id'])
  md_id = find_meta_datum(meta_key_id, md)&.fetch('id') ||
          create_meta_datum(meta_key_id, 'MetaDatum::Keywords', md)
  inserted = conn.exec_update(<<~SQL)
    INSERT INTO meta_data_keywords (meta_datum_id, keyword_id, created_by_id, position)
    SELECT #{q(md_id)}, #{q(kw_id)}, #{q(md['created_by_id'])},
           COALESCE((SELECT max(position) + 1 FROM meta_data_keywords WHERE meta_datum_id = #{q(md_id)}), 0)
    WHERE NOT EXISTS (SELECT 1 FROM meta_data_keywords
                      WHERE meta_datum_id = #{q(md_id)} AND keyword_id = #{q(kw_id)})
  SQL
  stats["#{meta_key_id} #{inserted.positive? ? 'assigned' : 'already assigned'}"] += 1
end

def check!
  KEYWORD_TARGETS.each_value do |id|
    mk = MetaKey.find_by(id: id)
    raise "#{id} missing, run #971 first" unless mk
    raise "#{id} is not of type Keywords" unless mk.meta_datum_object_type == 'MetaDatum::Keywords'
  end
  raise 'media_content:pages is not of type Text' unless MetaKey.find('media_content:pages').meta_datum_object_type == 'MetaDatum::Text'
  if (mk = MetaKey.find_by(id: DURATION)) && mk.meta_datum_object_type != 'MetaDatum::Text'
    raise "#{DURATION} exists but is not of type Text"
  end
end

def create_duration_key!
  if MetaKey.exists?(DURATION)
    puts "meta key exists: #{DURATION}"
    return
  end

  MetaKey.create!(id: DURATION,
                  vocabulary_id: 'media_content',
                  meta_datum_object_type: 'MetaDatum::Text',
                  text_type: 'line',
                  is_enabled_for_media_entries: true,
                  is_enabled_for_collections: true,
                  labels: DURATION_LABELS)
  puts "created meta key: #{DURATION}"
end

ActiveRecord::Base.transaction do
  report 'before'
  check!

  # resource creator as fallback for missing created_by
  source_data = conn.select_all(<<~SQL).to_a
    SELECT md.id, md.string, md.media_entry_id, md.collection_id,
           COALESCE(md.created_by_id, me.creator_id, c.creator_id) AS created_by_id
    FROM meta_data md
    LEFT JOIN media_entries me ON me.id = md.media_entry_id
    LEFT JOIN collections c ON c.id = md.collection_id
    WHERE md.meta_key_id = #{q(SOURCE)}
  SQL

  unmapped = source_data.map { |md| normalize(md['string']) }.uniq.reject { |v| mapping_for(v) }
  raise "values missing in MAPPING:\n#{unmapped.join("\n")}" if unmapped.any?

  puts
  create_duration_key!
  MetaKey.find(SOURCE).update!(labels: SOURCE_LABELS)
  puts "relabeled #{SOURCE}: #{SOURCE_LABELS}"

  source_data.each do |md|
    original = normalize(md['string'])
    row = mapping_for(original)

    TEXT_TARGETS.each do |col, meta_key_id|
      add_text(meta_key_id, md, row[col]) if row[col].present?
    end

    KEYWORD_TARGETS.each do |col, meta_key_id|
      row[col].to_s.split('; ').map(&:strip).reject(&:empty?).each do |term|
        add_keyword(meta_key_id, md, term)
      end
    end

    dimensions = row['dimensions'].to_s
    if dimensions.empty?
      conn.execute("DELETE FROM meta_data WHERE id = #{q(md['id'])}")
      stats["#{SOURCE} deleted"] += 1
    elsif dimensions != original
      conn.execute("UPDATE meta_data SET string = #{q(dimensions)} WHERE id = #{q(md['id'])}")
      stats["#{SOURCE} changed"] += 1
    else
      stats["#{SOURCE} unchanged"] += 1
    end
  end

  puts "\n== changes (#{source_data.size} #{SOURCE} meta_data processed)"
  stats.sort.each { |k, v| puts format('%-60s %5d', k, v) }

  # run deferred constraint triggers now instead of at commit
  conn.execute('SET CONSTRAINTS ALL IMMEDIATE')

  report 'after'

  if ENV['DRY_RUN'] == 'true'
    puts "\nDRY RUN - rolled back"
    raise ActiveRecord::Rollback
  else
    puts "\nCOMMITTED"
  end
end
